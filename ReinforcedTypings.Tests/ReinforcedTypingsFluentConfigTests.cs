	#region TsConst - value serialization

	[Fact]
	public void Configure_TsConstRichTypes_SerializesEveryFieldKindCorrectly()
	{
		string outDir = RtTestHarness.RunConfigure(ctx =>
		{
			ctx.Global.UseModules = true;
			ctx.Global.WriteWarningComment = false;
			ctx.Global.RootNamespace = ConstsRoot;
		});

		string content = RtTestHarness.ReadGenerated(outDir, "RichTypeConsts.ts");

		content.ShouldContain("Id: '11111111-1111-1111-1111-111111111111',");
		content.ShouldContain("CreatedAt: '2024-01-02T03:04:05.0000000Z',");
		content.ShouldContain("Day: '2024-01-02',");
		content.ShouldContain("Time: '03:04:05.0000000',");
		content.ShouldContain("Flag: true,");
		content.ShouldContain("Ratio: 3.14,");
		content.ShouldContain("Color: 1,"); // Plain enum (no [TsEnum]) always serializes numerically
		content.ShouldContain("Mode: 'Beta',"); // [TsEnum(UseString = true)]
		content.ShouldContain("Nothing: null,");
		content.ShouldContain("Numbers: [1, 2, 3],");
		content.ShouldContain("Tags: ['a', 'b'],");
		content.ShouldContain("Poco: { Label: 'x', Value: 7 },"); // Secret is [TsIgnore]d
	}

