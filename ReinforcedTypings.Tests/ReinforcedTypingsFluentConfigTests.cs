	#region TsConst - basic export modes

	[Fact]
	public void Configure_TsConstAll_ExportsUnignoredFieldsAsConstLiteral()
	{
		string outDir = RtTestHarness.RunConfigure(ctx =>
		{
			ctx.Global.UseModules = true;
			ctx.Global.WriteWarningComment = false;
			ctx.Global.TabSymbol = "\t";
			ctx.Global.NewLine = "\n";
			ctx.Global.RootNamespace = ConstsRoot;
		});

		string content = RtTestHarness.ReadGenerated(outDir, "BasicConstsAll.ts");

		// Field iteration order via reflection (GetFields) is not guaranteed, so assert on
		// content/structure rather than the full literal string.
		content.ShouldStartWith("export const BasicConstsAll = {\n");
		content.ShouldContain("\tTitle: 'Hello \\'World\\'',\n");
		content.ShouldContain("\tCount: 42,\n");
		content.ShouldContain("} as const;\n\n" +
			"export type BasicConstsAllKey = keyof typeof BasicConstsAll;\n" +
			"export type BasicConstsAllValue = (typeof BasicConstsAll)[BasicConstsAllKey];\n");
	}

